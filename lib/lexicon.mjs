/** يستخرج الكلمة بلا تشكيل ولا تطويل. */
export function bareWord(word) {
  return String(word ?? '')
    .replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .trim()
}

/** بلا تشكيل مع الحفاظ على الهمزات (حتى لا تختلط أبداً بـ أبدأ). */
function stripMarks(word) {
  return String(word ?? '').replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g, '').trim()
}

/** مفتاح مقارنة متسامح مع شكل الألف والتاء والياء. */
function looseKey(word) {
  return stripMarks(word).replace(/[أإآٱ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه')
}

let exactIndex = null
let looseIndex = null

function buildIndexes() {
  if (exactIndex) return
  exactIndex = new Map()
  looseIndex = new Map()
  const collisions = new Set()
  for (const [key, value] of Object.entries(GULF_TASHKEEL)) {
    const exact = stripMarks(key)
    exactIndex.set(exact, value)
    const loose = looseKey(key)
    if (looseIndex.has(loose) && looseIndex.get(loose) !== value) collisions.add(loose)
    looseIndex.set(loose, value)
  }
  // المفاتيح المتعارضة (أبداً/أبدأ) لا تُستخدم في المطابقة المتسامحة
  for (const key of collisions) looseIndex.delete(key)
}

/** بحث في قاموس التشكيل مع تجريد «ال» وحروف العطف. */
export function lookupTashkeel(token) {
  buildIndexes()
  const clean = stripMarks(token).replace(/[^\u0600-\u06FF]/g, '')
  if (!clean) return null

  const direct = exactIndex.get(clean) ?? looseIndex.get(looseKey(clean))
  if (direct) return direct

  if (clean.startsWith('ال') && clean.length > 3) {
    const stem = lookupTashkeel(clean.slice(2))
    if (stem) return `ال${stem}`
  }

  if (/^[وف]/.test(clean) && clean.length > 3) {
    const stem = lookupTashkeel(clean.slice(1))
    if (stem) return `${clean[0]}${stem}`
  }

  return null
}
