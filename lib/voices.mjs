export const DEFAULT_VOICE = 'ar-SA-HamedNeural'
export const DEFAULT_ENGLISH_VOICE = 'en-US-AvaMultilingualNeural'

export const ALL_VOICES = [...VOICES, ...ENGLISH_VOICES]

export function getVoice(id) {
  return ALL_VOICES.find((voice) => voice.id === id) ?? null
}

/** الصوت المناسب للغة الجملة. */
export function resolveVoice({ voice, englishVoice, language }) {
  if (language === 'en') return englishVoice || DEFAULT_ENGLISH_VOICE
  return voice || DEFAULT_VOICE
}
